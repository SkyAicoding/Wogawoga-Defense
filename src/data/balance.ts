/**
 * **생전 지급 몫** — 살아 있는 동안 받을 수 있는 bounty의 최대 비율(분자/분모).
 * 나머지는 사망 정산이 낸다. 총액은 **여전히 정확히 bounty**다(사망 시 잔액 전부).
 *
 * ⚠ **이 상수는 실측 스윕으로 유도됐다. 올리면 난이도 봉투가 빨개진다.**
 *
 * 스윕(스테이지1) — `autoplay.test.ts`의 **위험 5항목을 동시에** 측정했다.
 * `기준선`은 살점 값 적용 **전** 상태를 `git stash`로 되돌려 같은 시드로 잰 값이다:
 * ```
 *   생전몫  [1b]여유  [2]파괴  [3]minT  [7]지배  [12]입구요격
 *   ------  --------  -------  -------  -------  ------------
 *   기준선   54.9%     123      7        아님     52.5 ≤ 52.5   ← 변경 전 (문턱에 붙어 있다)
 *   1/1      59.5% ✗   113      7        아님     60.0 > 57.5 ✗
 *   3/4      55.2% ✗   119      5 ✗      아님     PASS
 *   2/3      54.3% ✓   103 ✓    7 ✓      기지자연  PASS         ← 채택
 *   1/2      52.8% ✓    89 ✗    6 ✗      기지자연  PASS
 *   1/4      51.9% ✓    88 ✗    7 ✓      아님     60.0 > 57.5 ✗
 * ```
 * ⚠ **어느 값도 5항목을 전부 통과시키지 못한다.** 봉투 여러 항목이 기준선에서 이미
 * 문턱에 정확히 붙어 있기 때문이다([3] 7 = 문턱 7 · [12] 52.5 = 문턱 52.5 ·
 * [1b] 54.9 대 55.0). 곧 이 봉투는 골드 곡선의 **어떤** 변화도 흡수하지 못한다.
 * ⚠⚠ **위 두 줄이 원래 이렇게 적혀 있었고, 그 진단은 폐기됐다** (정직성 정리 라운드):
 *   "2/3에서 남은 [7]은 **지표의 오독**이었고(마을 갈래의 여유가 baseHpMax에 오염된다),
 *    그 항목 주석이 미리 적어 둔 재유도 지침대로 두 번째 다리를 절대 누수 피해로
 *    바꿔서 해결했다 — 문턱 완화가 아니다."
 * **그 지표 교체는 그 다음 라운드가 되돌렸다.** 절대 누수 피해는 마을을 사는 전략과
 * 부호가 구조적으로 반대라(오래 버틸수록 흡수한 총량이 커진다) 9단계가 게임을 고쳐서
 * 껐던 **문서화된 지배 전략조차 독립 4블록 0/4로 못 잡는다** = 판별력이 0이다.
 * 두 번째 다리는 원래의 `slackAvg`로 돌아가 있고, [7]을 실제로 끈 것은 지표가 아니라
 * **마을 비용 표**다(600/900/1300/1700 → 900/1000/1200/1400, 누적 4,500 불변 —
 * 유도 전문은 `src/data/hometown.ts`의 '살점 값 단계' 절).
 * 곧 이 스윕표의 `[7]` 열은 **그때 쓰던 지표로 읽은 값**이고, 지금 지표로 다시 읽으면
 * 2/3 · 옛 비용표에서 [7]은 blk1000이 적색이었다. 되돌리기 실측 전문은
 * `autoplay.test.ts`의 7번 항목 주석에 있다.
 *
 * 원인은 총량이 아니라 **시점**이다:
 * STRONG_BOT의 총수입 증가는 **+1.5%**뿐인데 그 돈이 **보스 웨이브 도중**에 들어와
 * 대공 타워가 한 박자 일찍 서고, 그러면 하늘길(w22·26·34·38·42·46)이 기지 체력을
 * 못 가져간다(종료 HP에 22~25가 대량 등장). 곧 이 봉투는 골드의 **양이 아니라
 * 도착 시각**에 민감하다.
 *
 * 그래서 문턱을 내리는 대신 **게임 쪽을 고쳤다**: 생전 지급을 깎아 조기 수입 우위만
 * 정확히 겨냥한다. 지급 **횟수**는 그대로다 — 한 몫의 최솟값이 `MIN_GOLD × 2/3` = 2.67
 * 골드라 1 미만으로 내려가는 몫이 없고, 곧 몫 경계가 하나도 안 사라진다.
 * 이 변경이 고치려던 "무수입 구간의 길이"는
 * 손대지 않으면서 봉투만 되돌린다. `BOUNTY_CHUNK_MAX`를 줄이는 손잡이보다 나은
 * 이유가 이것이다 — 그쪽은 공백 단축 효과를 직접 반납한다.
 *
 * 1/3이 1/2보다 **더 나쁜 것**에 주의하라(입구요격이 깨진다). 이 지형은 단조롭지 않다 —
 * 봇이 문턱을 넘는 시점이 이산적이라 돈이 줄어도 결과가 뒤집힐 수 있다.
 * 값을 바꾸려면 반드시 위 두 항목을 **함께** 다시 재라.
 *
 * 부수 효과로 **"죽여야 제값을 받는다"가 세진다** — 원시시대 사냥의 뜻과도 맞고,
 * 딜만 넣고 못 죽이는 배치(입구 요격)가 받던 이득을 정확히 그만큼 깎는다.
 */
export const BOUNTY_CHUNK_LIVE_NUM = 2;
export const BOUNTY_CHUNK_LIVE_DEN = 3;

/**
 * 몫 수 K — 이 개체가 **이번 웨이브의 표준 사냥감 몇 마리분인가**. 스폰 시 한 번 굳는다.
 *
 * 세 상한의 min 이고, 각각 다른 것을 막는다:
 *  · `round(maxHp / refHp)` — 덩치. 이게 본체다. 잡몹이면 1이 되어 **오늘과 같은 동작**.
 *  · `floor(bounty / BOUNTY_CHUNK_MIN_GOLD)` — 한 몫이 4골드 밑으로 안 내려간다.
 *  · `BOUNTY_CHUNK_MAX` — 이벤트 수와 "한 입의 체감"의 상한.
 *
 * **무한 모드(HP 1.06^n)에 완전히 불변이다**: maxHp 도 refHp 도 같은 extraHpMul 을 지고
 * 있어 분자·분모가 함께 커진다. 곧 개체당 지급 **횟수**가 웨이브와 무관하게 고정이고,
 * 수입의 리듬이 무한 모드에서도 유지된다. (남는 것: 몫 하나가 씹어야 하는 HP 는 계속
 * 커진다 — b/HP 가 w1 0.1176 → w50 0.0175 로 떨어지는 기울기는 **일부러** 안 고친다.
 * 이 변경의 렌즈는 "언제 주는가"이지 "얼마를 주는가"가 아니고, 후자는 총량 보존을
 * 정면으로 깨는 별개 결정이다.)
 */
export function bountyChunksFor(maxHp: number, bounty: number, refHp: number): number {
  const byBulk = Math.round(maxHp / Math.max(1, refHp));
  const byGold = Math.floor(bounty / BOUNTY_CHUNK_MIN_GOLD);
  return Math.max(1, Math.min(byBulk, byGold, BOUNTY_CHUNK_MAX));
}

