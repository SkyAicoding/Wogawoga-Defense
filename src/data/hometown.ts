/**
 * 홈타운(기지) 레벨 5단계 — 움막 하나에서 시작해 골드로 키우는 **최후 방어선**.
 * 행동 규칙 전문은 src/sim/hometown.ts 헤더. 여기는 수치와 그 근거만 적는다.
 *
 * ── 왜 5레벨인가 ───────────────────────────────────────────────────────────
 * 타워가 정확히 5티어(전투 내 Lv1~5)다. 같은 칸 수를 쓰면 HUD의 "Lv 3/5"가 두 곳에서
 * 같은 뜻이 되고, 비용 배증(×2)도 타워 티어 곡선과 그대로 겹쳐 읽힌다.
 * 전투 중 진행이라 전투가 끝나면 Lv1로 돌아간다 — 메타 진행(별)이 아니다.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 5단계 개정 — "HP를 파는 상품"에서 "화력을 파는 상품"으로
 * ═══════════════════════════════════════════════════════════════════════════
 * 4단계까지의 표는 hpMul 1.0→3.2 · dmg 8→36 · 사거리 2.0→3.0 이었다. 검증에서
 * 세 가지가 동시에 드러났고, 셋 다 **같은 하나의 기전**에서 나왔다:
 *
 *  (1) Lv2가 지배 전략이었다. 봉투 시드 40개에서 타워 몰빵 36/40승·잔여HP 8.3 대
 *      Lv2까지만 올린 봇 38/40승·잔여HP 16.1 — 골드의 1.3%(300)를 내고 **승수와 여유를
 *      동시에** 이겼다. 불도저 항목이 정확히 이 형태를 금지하는데(autoplay 6번) 마을에는
 *      그 잣대가 없었다.
 *  (2) 공격력·사거리 상승분의 효과가 0이었다. Lv2의 dmg/사거리만 Lv1 값으로 고정한
 *      위약과 정품이 **모든 자릿수까지 동일**했다(38/40 · 웨평 49.92 · 누수 755).
 *  (3) Lv4·5가 어떤 스윕에서도 도달되지 않아 비용 곡선의 뒤 80%가 미측정이었다.
 *
 * **기전**: 기지 사거리 안에 든 적은 어차피 1~3초 뒤 누수되어 사라지고, 누수 피해는
 * 적의 남은 HP와 무관하다. 즉 **죽이지 못한 피해는 시뮬레이션에 아무 흔적도 남기지
 * 않는다.** 사거리 3.0 · 60dps로는 후반 적을 죽일 수 없으므로 공격력을 올려도
 * 아무 일이 없었고, 그래서 이 상품이 실제로 팔던 것은 오직 HP였다. 그런데 스테이지1
 * baseHp가 25뿐이라 +10 HP는 완충의 40%다 — 300골드에 그걸 파니 정답일 수밖에 없다.
 *
 * 그래서 파는 물건을 바꿨다. **HP는 얕게(레벨당 +12%), 화력은 실제로 죽일 수 있을
 * 만큼**(dps 8 → 168, 사거리 2.0 → 4.6). 실측 결과는 각 항목에 아래에 적는다.
 *
 * ── 최대 HP: ×1.0 → ×1.48 (레벨당 +0.12) ───────────────────────────────────
 * 스테이지1(baseHp 25) 기준 **25 / 28 / 31 / 34 / 37**. 레벨당 정확히 +3.
 * 3.2배(25→80)에서 1.48배로 내렸다. 근거는 위 (1)이다 — HP는 이 게임에서 값을 매기기
 * 가장 어려운 물건이다. 누수 피해가 랩터 1 · 매머드 3 · 티라노 10이라 +10 HP는
 * 초반이면 랩터 열 마리, 후반이면 티라노 한 마리이고, 어느 쪽이든 **패배를 직접
 * 유예**하므로 승률로 환산하면 언제나 타워보다 싸게 먹힌다.
 * 실측(봉투 시드 40, 타워 몰빵 기준선 36/40승·잔여 8.3):
 *   개정 전 Lv2까지  38/40 · 16.1   ← 승수·여유 동시 우위 = 지배 전략
 *   개정 후 Lv2까지  36/40 ·  9.3   ← 승수 동률
 *   개정 후 살 수 있으면 산다(Lv3까지 자연 도달)  35/40 · 12.1  ← 승수 −1
 * "사면 좋지만 사도 이기는 판이 늘지는 않는다"가 이 곡선이 서 있어야 할 자리다.
 *
 * ── 공격력: Lv1 8dps → Lv5 168dps ─────────────────────────────────────────
 * dmg 8/18/34/56/84, 쿨다운 30/24/20/17/15틱 → 8 / 22.5 / 51 / 98.8 / 168 dps.
 * · Lv1 8dps는 그대로 뒀다. 가장 싼 공격 타워(창움막 T1 24dps)의 1/3이라 혼자서는
 *   아무것도 못 잡고 "깎여 온 놈의 마지막 한 대"를 보탠다. 방치(타워 0) 봇이 지금도
 *   웨이브 8에 지는 것으로 잠가 뒀다(autoplay 5번).
 * · Lv5 168dps는 창움막 만렙(177dps)과 맞먹는다. 4단계의 60dps에서 2.8배 올렸다.
 *   **올려야만 이 상품이 존재하기 때문이다** — 위 기전대로, 죽이지 못하는 화력은
 *   문자 그대로 0이다. 실측(봉투 시드 40, 만렙까지 모아 사는 봇):
 *     화력 성장 O → 17/40승 · 웨평 46.73 · 기지 처치 1,751
 *     화력 성장 X(공격력·사거리를 Lv1에 고정) → 7/40승 · 웨평 39.52 · 기지 처치 53
 *   같은 골드를 쓰고 **+10승 · +7.2웨이브**다. 개정 전 같은 A/B는 15승 대 16승으로
 *   부호조차 뒤집혀 있었다(= 무의미).
 *
 * ── 사거리: 2.0 → 4.6 ──────────────────────────────────────────────────────
 * · Lv1 2.0은 **4단계에서 한 톨도 바꾸지 않았다.** 시작 상태는 모든 스테이지·모든
 *   기준선 측정의 원점이라, 여기를 건드리면 이번 개정과 무관한 숫자까지 전부 움직여
 *   before/after 를 읽을 수 없게 된다. 여전히 쏘는 타워 전부(최소 frost T1 2.4)보다 짧다.
 * · 만렙 4.6은 들판 타워(창움막 3.0 / 투석기 3.6 / 번개 3.2)보다는 길고 **발리스타
 *   (5.5~5.7)보다는 짧다**. 4단계의 3.0에서 올린 이유는 화력과 같다: 사거리가 곧
 *   체류 시간이고, 체류 시간이 짧으면 dps를 아무리 올려도 한 마리를 못 죽인다.
 *   랩터(1.6타일/초) 기준 사거리 2.0은 1.25초 = 화살 1~2발이지만 4.6은 2.9초 = 8발이다.
 * · 그래도 **자리를 고르는 판단은 죽지 않는다**: 홈타운은 경로 끝에 붙박여 있어
 *   덮는 구간이 언제나 "마지막 4.6타일" 하나뿐이고, 경로가 여럿인 스테이지에서는
 *   그마저 갈린다. 타워는 어디든 갈 수 있고 발리스타는 5.7까지 본다.
 *
 * ── 비용: 300 / 600 / 1200 / 2400 (누적 4,500) ─────────────────────────────
 * 타워 티어 비용처럼 정확히 배증한다. 4단계에서 정한 값을 그대로 뒀다 —
 * 이번 개정은 **가격이 아니라 물건**을 바꿨기 때문이다.
 * 화력 단가로는 여전히 타워보다 나쁘다: 누적 4,500골드에 168dps = 26.8골드/dps이고
 * 창움막 만렙은 3,100골드에 177dps = 17.5골드/dps다(1.5배 비싸다). 그 대신 홈타운은
 * 칸을 먹지 않고, 습격대에게 부서지지 않으며, 저주(침묵)도 걸리지 않고, HP도 같이 산다.
 *
 * ── Lv4·5는 이제 측정된다 (개정 전에는 불가능했다) ──────────────────────────
 * 봇이 Lv4(1,200)에 한 번도 닿지 못했던 것은 값이 비싸서가 아니라 **봇이 모을 줄
 * 몰라서**였다: 외곽 루프가 매 회 잔고를 타워 업그레이드로 훑어 가므로 "지금 못 사는
 * 것"은 영원히 못 산다. 하네스에 `base.save`(다음 레벨 값을 타워가 못 쓰게 잠근다)를
 * 넣자 Lv5까지 도달했고, 그때의 답은 **"만렙까지 모아 사는 것은 나쁜 수"**다
 * (17/40승 대 타워 몰빵 36/40). 즉 곡선의 뒤쪽은 함정이 아니라 **비상용 상한**이다 —
 * 무한 모드처럼 골드가 남아도는 판에서만 값이 선다.
 */
