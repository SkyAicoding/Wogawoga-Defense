/**
 * 홈타운(기지) 레벨 5단계 — 움막 하나에서 시작해 골드로 키우는 **최후 방어선**.
 * 행동 규칙 전문은 src/sim/hometown.ts 헤더. 여기는 수치와 그 근거만 적는다.
 *
 * ── 왜 5레벨인가 ───────────────────────────────────────────────────────────
 * 타워가 정확히 5티어(전투 내 Lv1~5)다. 같은 칸 수를 쓰면 HUD의 "Lv 3/5"가 두 곳에서
 * 같은 뜻이 되고, 비용 배증(×2)도 타워 티어 곡선과 그대로 겹쳐 읽힌다.
 * 전투 중 진행이라 전투가 끝나면 Lv1로 돌아간다 — 메타 진행(별)이 아니다.
 *
 * ── 사거리: 2.0 → 3.0 (쏘는 타워 전부보다 안쪽) ────────────────────────────
 * **쏘는** 타워(homing/ballistic/beam)의 사거리는 2.4(frost T1) ~ 5.7(ballista T5)이다.
 * Lv1의 2.0은 **그 전부보다 짧다** — 홈타운이 사거리로 타워를 대체할 수 없다는 뜻이고,
 * 화면에서도 "마당 안에 들어온 놈만 쏜다"로 읽힌다. 만렙 3.0조차 창움막 만렙과 같고
 * 발리스타(5.7)의 절반이다. 즉 홈타운은 아무리 키워도 **자기 문간**만 지킨다.
 * (오라형 brazier 1.8 / drum 2.0은 이 비교에서 뺀다 — 그건 조준해서 쏘는 사거리가 아니라
 *  반경 안을 통째로 지지는 장판/버프 반경이라 성격이 다르다)
 *
 * 시간으로 환산하면 Lv1은 적이 마지막 2타일을 지나는 동안뿐이다:
 * 랩터(1.6타일/초)면 1.25초, 트라이크(0.7)면 2.9초. 만렙 3.0이면 각각 1.9초·4.3초.
 *
 * 출격 한계선(ALLY_SORTIE_RANGE 6.0)과도 겹치지 않는다 — 아군 부족원은 기지에서
 * 6타일 앞에 줄을 서므로, 홈타운의 화살이 닿는 곳까지 적이 왔다는 건
 * **아군 줄이 이미 뚫렸다**는 뜻이다. 세 겹(타워 → 아군 → 홈타운)이 거리로 분리된다.
 *
 * ── 공격력: Lv1 8dps → Lv5 60dps ───────────────────────────────────────────
 * · Lv1 8dps(8피해 / 1초)는 창움막 T1(12/0.5초 = 24dps)의 **1/3**이다.
 *   랩터(hp 60)가 사거리를 지나는 1.25초에 화살 1~2발 = 8~16피해, 체력의 13~27%.
 *   혼자서는 아무것도 못 잡고 **깎여 온 놈의 마지막 한 대**를 보탠다.
 *   → "있으나 마나"를 피하면서 초반 자동 클리어도 피하는 자리다. 실측으로 잠가 뒀다:
 *     타워 0기 방치 봇은 홈타운이 쏘는 지금도 웨이브 10 안에 진다
 *     (tests/sim/autoplay.test.ts '방치(타워 0)면 웨이브 10 안에 패배').
 * · Lv5 60dps는 창움막 만렙(65/0.37초 = 177dps)의 약 1/3이다. 만렙 비용이
 *   3,300골드로 창움막 하나를 만렙까지 올리는 값(3,100)과 거의 같은데 화력은 1/3 —
 *   **화력 단가로는 언제나 손해**다. 그 대신 홈타운은 칸을 먹지 않고, 습격대에게
 *   부서지지 않으며, 저주(침묵)도 걸리지 않고, HP까지 같이 산다. 즉 이 값은
 *   "화력을 사는 값"이 아니라 **보험료**다.
 *
 * ── 최대 HP: ×1.0 → ×3.2 ───────────────────────────────────────────────────
 * 스테이지1(baseHp 25) 기준 25 / 35 / 48 / 63 / 80.
 * 절대량이라 후반 적일수록 값이 떨어진다 — 누수 피해가 랩터 1, 매머드 3, 티라노 10이라
 * 초반에 산 +10은 랩터 10마리지만 후반엔 티라노 한 마리다. 이 자연 감가가
 * "HP는 미리 사 두는 것"이라는 결을 만들고, 후반 레벨업의 값어치는 공격력 쪽으로 넘어간다.
 *
 * ── 비용: 220 / 440 / 880 / 1760 (누적 3,300) ──────────────────────────────
 * 타워 티어 비용처럼 정확히 배증한다. 스테이지1 시작 골드가 300이라 첫 레벨업(220)은
 * "시작하자마자 타워 두 기를 포기한다"는 값이고, 웨이브 1~50 클리어 보상 합이
 * 9,150이라 만렙(3,300)은 그 36%다 — 타워를 아예 안 키우겠다는 각오 없이는 못 간다.
 */
