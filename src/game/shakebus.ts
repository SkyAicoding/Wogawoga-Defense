/**
 * **화면 흔들림 2채널** — 큰 사건만 판을 흔든다.
 *
 * ── 왜 별도 모듈인가 ───────────────────────────────────────────────────────
 * 규칙이 `fx.ts` 안의 두 private 메서드였을 때 **아무 계약도 못 걸었다**(FxRouter 는
 * Stage3D·카메라·캔버스를 다 요구해서 단위 테스트에 세울 수 없다). 그 사이 이 자리에서
 * 실제로 두 번 틀렸다 — 한 번은 출시본에서(피해에 비례한 착탄 셰이크), 한 번은 그걸
 * 고치는 첫 판에서(배치당 예산은 프레임레이트가 오르면 상한 구실을 못 한다).
 * 그래서 규칙만 떼어 **의존성 0 · 시계 주입 가능**하게 만들었다. `tests/render/shakebus.test.ts`
 * 가 잠그는 것이 곧 사용자의 요구문이다.
 *
 * ── 사용자 요구 (원문) ────────────────────────────────────────────────────
 * "지금은 적을 공격할 때마다 판 전체가 지진이 나는 효과가 나는데, 이거 효과를 좀
 *  줄여줘. 크리티컬 한 경우에만 지진 효과를 넣어줘, 그렇지 않을 때는 효과를 지금보다
 *  작게 하거나, 고정 시켜서. 판 전체를 너무 흔들면 게임 중에 어지러워."
 *
 * ⚠ 이 게임에 **크리티컬 히트는 없다**(`src/sim` 에 crit 개념이 없다). 여기서
 *   "크리티컬"은 **큰 사건**으로 읽었다 — 보스, 타워 파괴, 마을이 크게 뚫림.
 *
 * ── 두 채널 ────────────────────────────────────────────────────────────────
 *  · `quake(세기)` — 큰 사건. 세기는 **종전 그대로**다(줄여야 하는 건 큰 사건이 아니다).
 *    한 배치(=한 프레임) 총량만 `QUAKE_BUDGET` 으로 막는다. 잦지 않으므로 그것으로 족하다.
 *  · `tap(무게)` — 잦은 사건(착탄). **피해·티어·타워 종류를 안 보는 고정값**이고,
 *    `TAP_MIN_MS` 시계 스로틀로 초당 주입량을 잠근다.
 *
 * ── ⚠ 왜 잦은 채널은 예산이 아니라 시계인가 (여기가 이 파일의 핵심이다) ──────
 * 카메라 진폭은 배치마다 초기화되지 않고 **쌓인다** — `camera.shake` 는
 * `amp = min(1, amp + s)` 이고 감쇠는 `exp(−6·dt)` 다. 그러면 정상 상태 진폭을 정하는
 * 것은 프레임당 주입량이 아니라 **초당 주입량**이라, 배치 예산은 프레임레이트가
 * 오르면 그만큼 초당 주입량이 늘어 상한 구실을 못 한다. 60fps 실측 계산:
 * ```
 *   구: 예산 0.5/프레임          → amp 1.000 (포화) · 오프셋 0.3500
 *   구: 투석기 착탄 0.284 × 4/초  → amp 0.366        · 오프셋 0.1279  ← 실제 체감
 *   안(예산 0.05/프레임)          → amp 0.525        · 오프셋 0.1839  ← 안 줄었다
 *   **채택(120ms 스로틀 ≤8.3/초)  → amp 0.035        · 오프셋 0.0123**
 * ```
 * 곧 실제 체감 기준 약 **1/10**, 종전 최악 기준 약 1/28 이다.
 */

/**
 * 큰 사건 채널의 한 배치 총량. **구 단일 채널과 같은 0.5 로 둔다.**
 *
 * ⚠ 0.34 로 조였다가 계약이 잡아냈다 — 판에서 가장 큰 단일 사건인 보스 등장이
 *   `quake(0.4)` 라 **예산에 잘려 0.34 로 나갔다.** 예산의 일은 여럿이 겹칠 때를
 *   막는 것이지 가장 큰 하나를 깎는 것이 아니고, 이 라운드가 줄이려는 것도 큰
 *   사건이 아니다. 게다가 잦은 사건이 이 채널을 떠난 뒤로 여기가 찰 일 자체가
 *   드물다(보스 등장과 보스 처치가 같은 프레임에 오지는 않는다).
 */
export const QUAKE_BUDGET = 0.5;
/** 이보다 작은 큰-사건 요청은 카메라까지 안 간다 (감쇠에 묻힌다) */
export const QUAKE_MIN = 0.002;
/** 잦은 사건 1회당 **고정** 세기 — 피해·티어·타워 종류를 안 본다 */
export const TAP_SHAKE = 0.018;
/**
 * 잦은 사건 셰이크의 최소 간격 (ms). 120 은 착탄음(boulderImpact)이 겹쳐 들리기
 * 시작하는 간격과 같은 자리라 한 톡이 소리 한 번에 대응한다. 이 간격 안에 들어온
 * 착탄은 **소리와 파티클은 그대로 나가고 셰이크만 생략된다** — 사건이 사라지는 게
 * 아니라 화면만 안 흔들린다.
 */
export const TAP_MIN_MS = 120;

/** 카메라로 나가는 출구 — 테스트는 여기에 기록기를 꽂는다 */
export type ShakeSink = (amount: number) => void;

export class ShakeBus {
  /** 이번 배치에서 큰 사건이 쓴 총량 */
  private quakeSpent = 0;
  /** 마지막 잦은-사건 톡 시각 (ms) */
  private tapAt = -1e9;

  constructor(
    private readonly sink: ShakeSink,
    /** 시계 주입 — 기본은 실시간. 테스트가 시간을 손으로 민다 */
    private readonly now: () => number = () => performance.now(),
  ) {}

  /** 한 배치(=한 프레임)의 시작 — 큰 사건 예산만 초기화한다(톡 스로틀은 시계다) */
  beginBatch(): void {
    this.quakeSpent = 0;
  }

  /**
   * **큰 사건** — 보스·타워 파괴·마을 돌파처럼 판에서 몇 번 안 나는 사건 전용.
   * 잦은 사건은 여기 오면 안 된다 (`tap()` 을 쓴다).
   */
  quake(amount: number): void {
    if (amount <= QUAKE_MIN) return;
    const left = QUAKE_BUDGET - this.quakeSpent;
    if (left <= 0) return;
    const a = Math.min(amount, left);
    this.quakeSpent += a;
    this.sink(a);
  }

  /**
   * **잦은 사건** — 고정 세기 `TAP_SHAKE × weight`, `TAP_MIN_MS` 시계 스로틀.
   * 피해량을 인자로 안 받는 것이 요점이다: 받는 순간 후반 타워가 곧 지진이 된다.
   * `weight` 는 사건 종류의 무게만 준다(착탄 1, 지형 정리 2 — 잦기가 다르다).
   * 스로틀이 배치 예산을 겸한다 — 한 프레임에 열 발이 들어와도 톡은 한 번이다.
   */
  tap(weight = 1): void {
    const t = this.now();
    if (t - this.tapAt < TAP_MIN_MS) return;
    this.tapAt = t;
    this.sink(TAP_SHAKE * weight);
  }
}
