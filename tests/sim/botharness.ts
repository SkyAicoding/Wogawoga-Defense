/**
 * 봇 1판 실행. 외곽 루프 1회 = 커맨드 한 묶음 + 120틱.
 * 파괴로 타워 수가 줄면 배치 루프가 자동으로 빈 자리를 채운다(= 재건설).
 */
export function runBot(sim: BattleSim, stage: StageDef, opts: BotOptions = {}): BotResult {
  const bulldoze = opts.bulldoze === true;
  const hugPath = opts.hugPath === true;
  const maxIters = opts.maxIters ?? 900;
  const cap = opts.cap ?? PLACEMENT_CAP;
  const samples = pathSamples(stage);
  const dist = pathDistances(stage, samples);
  const cells: [number, number][] = [];
  for (let z = 0; z < stage.gridH; z++) {
    for (let x = 0; x < stage.gridW; x++) {
      if (sim.canPlaceAt(x, z) || (bulldoze && sim.hasScenery(x, z))) cells.push([x, z]);
    }
  }
  const distOf = ([x, z]: [number, number]): number => dist[z * stage.gridW + x] as number;

  // ── 커버 계산 (placement 'cover'/'kill' 전용, 'near'에서는 한 번도 호출되지 않는다) ──
  const placeMode: PlacementMode = opts.placement ?? 'near';
  const nSamples = samples.xs.length;
  /** (셀, 사거리) → 그 원 안에 든 경로 샘플 인덱스. 셀×사거리 조합이 유한해 캐시 하나면 끝난다 */
  const coverCache = new Map<string, Int32Array>();
  const coveredBy = (cx: number, cz: number, r: number): Int32Array => {
    const key = `${cx},${cz},${r}`;
    const hit = coverCache.get(key);
    if (hit) return hit;
    const idx: number[] = [];
    const r2 = r * r;
    for (let i = 0; i < nSamples; i++) {
      const dx = (samples.xs[i] as number) - cx;
      const dz = (samples.zs[i] as number) - cz;
      if (dx * dx + dz * dz <= r2) idx.push(i);
    }
    const out = Int32Array.from(idx);
    coverCache.set(key, out);
    return out;
  };
  const rangeOf = (def: TowerDef): number => def.tiers[0]?.range ?? 2.5;
  /** 지금 서 있는 타워들이 각 경로 샘플을 몇 겹으로 덮고 있는가 (배치 판정 직전에 갱신) */
  const coverCount = new Int32Array(nSamples);
  const recountCover = (): void => {
    coverCount.fill(0);
    for (const t of sim.state.towers) {
      const d = TOWER_DEFS[t.defId];
      if (!needsPathCoverage(d)) continue;
      for (const i of coveredBy(t.cellX, t.cellZ, rangeOf(d))) coverCount[i] = (coverCount[i] as number) + 1;
    }
  };
  /**
   * 0등급 안쪽 순위. 'cover'는 커버 길이, 'kill'은 **겹침을 가중한** 커버 길이다
   * (그 샘플을 이미 덮는 타워 한 기당 +0.5배). 둘 다 클수록 좋으므로 부호를 뒤집는다.
   */
  const grade0Of = (def: TowerDef, cx: number, cz: number): number | undefined => {
    if (placeMode === 'near') return undefined;
    const idx = coveredBy(cx, cz, rangeOf(def));
    if (placeMode === 'cover') return -idx.length * PATH_SAMPLE_STEP;
    let w = 0;
    for (const i of idx) w += 1 + 0.5 * (coverCount[i] as number);
    return -w * PATH_SAMPLE_STEP;
  };
  const keyOf = (def: TowerDef, c: [number, number]): number =>
    placementKey(def, distOf(c), hugPath, grade0Of(def, c[0], c[1]));

  let clears = 0;
  let clearGold = 0;
  let destroyed = 0;
  let placed = 0;
  let lostTiers = 0;
  let lostGold = 0;
  let minTowers = Infinity;
  let goldTowers = 0;
  let goldAllies = 0;
  let goldBase = 0;
  let alliesTrained = 0;
  let allyDeaths = 0;
  let allyTicks = 0;
  let allyBlockTicks = 0;
  let enemyBlockedTicks = 0;
  let allyBlockMinDist = Infinity;
  let baseShots = 0;
  let baseDamage = 0;
  let baseKills = 0;
  let leaked = 0;
  // 문간 계측 — `gateEnter` 는 개체별 **마지막으로 관측된 체류 틱**이다.
  // `enemyDied` 는 체류 틱을 직접 싣지만(combat.ts) `enemyLeaked` 는 안 실으므로,
  // 돌파한 개체의 체류는 마지막 한 입의 `gateTicks` 로 근사한다 — 상한(baseDamage × 30)
  // 안에서 마지막 입이 나가므로 오차는 언제나 한 주기 미만이다.
  let gateStints = 0;
  let gateTicksSum = 0;
  let gateBites = 0;
  let gateKills = 0;
  const gateEnter = new Map<number, number>();
  let leaks = 0;
  /** 적 id → 마지막으로 피해를 준 출처. enemyDied에 출처가 없어 여기서 귀속시킨다 */
  const lastHit = new Map<number, string>();
  /** 봉쇄 중인 아군 id 집계용 스크래치 (매 틱 재사용 — 할당 없음) */
  const engaged = new Set<number>();
  /** 틱 진행 직전 스냅샷 — 파괴 이벤트에는 invested가 없으므로 여기서 조회한다 */
  const investedById = new Map<number, number>();

  // ── T0 신설 계측 (전부 **래핑뿐**. sim 호출의 순서·인자·횟수가 한 자리도 안 바뀐다) ──
  const cmdCounts = new Map<string, number>();
  let cmdTotal = 0;
  let goldFromCommands = 0;
  let goldFromTicks = 0;
  let brokeTicks = 0;
  let totalTicks = 0;
  let brokeRunMax = 0;
  let brokeRun = 0;
  let brokePriceMin = Infinity;
  let brokePriceMax = 0;
  let gatherGold = 0;
  let gatherLoads = 0;
  let gatherDeliveries = 0;
  let gatherLostGold = 0;
  let gatherDeaths = 0;
  let gatherEvents = 0;
  /** 판 끝 스냅샷이 아니라 **이벤트 누적**이다 — 재생이 그 등식을 깼다(BotResult.harvests) */
  let harvests = 0;
  let regrows = 0;
  let allyGatherTicks = 0;
  /** 웨이브대 5칸 — [w1-10, w11-20, w21-30, w31-40, w41-50] */
  const gatherGoldByBand = [0, 0, 0, 0, 0];
  const bandOf = (wave: number): number => Math.min(4, Math.max(0, Math.floor((wave - 1) / 10)));

  /**
   * **커맨드 래퍼** — `sim.applyCommand`를 그대로 부르고 앞뒤로 세기만 한다.
   * 골드 차가 양수면 그 커맨드가 **수입을 낸 것**이다(조기 호출 보너스 · 판매 환불).
   * 이 함수를 통하지 않는 `applyCommand` 호출이 runBot 안에 남으면 표가 조용히 새므로,
   * 이 파일에는 `sim.applyCommand(` 가 **여기 한 줄만** 있어야 한다.
   */
  const cmd = (c: BattleCommand): boolean => {
    const before = sim.state.gold;
    const ok = sim.applyCommand(c);
    const delta = sim.state.gold - before;
    if (delta > 0) goldFromCommands += delta;
    if (ok) {
      cmdCounts.set(c.type, (cmdCounts.get(c.type) ?? 0) + 1);
      cmdTotal++;
      menuStale = true;
    }
    return ok;
  };

  /**
   * **지금 살 수 있는 가장 싼 매물** — 무일푼 판정의 자. 범위와 제외 근거는
   * `BotResult.brokeTicks` 주석에 있다(타워 업그레이드·소품 제거는 뺐다).
   * 매물이 하나도 없으면 0을 돌려준다 = "무일푼일 수 없다"(살 것이 없으면 가난이 아니다).
   */
  const menuPrice = (): number => {
    const st = sim.state;
    let m = Infinity;
    for (const c of st.hand) if (c) m = Math.min(m, c.cost);
    if (st.allies.length < sim.allyCap()) {
      for (const id of Object.keys(ALLY_DEFS) as AllyId[]) m = Math.min(m, sim.allyCost(id));
    }
    const b = sim.baseUpgradeCost();
    if (b !== null) m = Math.min(m, b);
    if (st.refreshCost > 0) m = Math.min(m, st.refreshCost);
    return m === Infinity ? 0 : m;
  };
  let menuNow = 0;
  let menuStale = true;

  // ── 아군/기지 정책 준비 ────────────────────────────────────────────────────
  /** 경로별 총 길이 — 적의 '기지까지 남은 거리' = totalLength − enemy.dist */
  const pathLens = stage.paths.map((wp) => buildPath(wp).totalLength);
  /**
   * **하늘길의 총 길이** — 비행 적의 '기지까지 남은 거리'는 지상 경로로 재면 틀린다.
   *
   * 왜 필요한가 (15단계에서 고친 자의 버그): 비행 적의 `pathIndex`는 **airPaths의**
   * 인덱스이고, 하늘길은 지상 경로와 길이가 전혀 다르다(스테이지1 설계에서 17.0 대 36.19).
   * 지상 표로 빼면 남은 거리가 두 배로 부풀어, 마을 문턱에 닿은 비행 적이
   * "아직 한참 멀다"로 읽힌다. sim과 **같은 폴백**(airPaths가 없으면 스폰→기지 직선,
   * 인덱스 초과는 0번)을 그대로 쓴다 — 두 곳이 다른 경로를 보면 트리거가 거짓말을 한다.
   */
  const airLens =
    stage.airPaths && stage.airPaths.length > 0
      ? stage.airPaths.map((wp) => buildPath(wp).totalLength)
      : stage.paths.map((wp) => buildStraight(wp[0] ?? stage.baseCell, stage.baseCell).totalLength);
  const allyPolicy = opts.allies;
  /**
   * 감시 창의 길이. 9단계에 출격 한계선이 삭제되면서 **판정마다 다시 읽을 이유가
   * 없어졌다**(마을 레벨을 따라 자라던 값이 사라졌다) — 이제 판 내내 상수다.
   */
  const allyTrigger = allyPolicy?.trigger ?? ALLY_WATCH_WINDOW;
  const allyMinNear = Math.max(1, allyPolicy?.minNear ?? 1);
  /**
   * 밀도 보존 — 창을 넓히면 문턱도 같은 비율로 올린다 (ALLY_WATCH_WINDOW 주석).
   * 기본 창에서는 비율이 정확히 1이라 minNear가 그대로 쓰인다.
   */
  const allyMinNearNow = Math.max(1, Math.round((allyMinNear * allyTrigger) / ALLY_WATCH_WINDOW));
  const allyReserve = allyPolicy?.reserve ?? 0;
  const allyStance: AllyStance = allyPolicy?.stance ?? 'home';
  /**
   * 'front' 팔이 찍는 셀 = **지상 경로의 첫 웨이포인트 = 적 스폰 셀**.
   * "입구 요격"을 문자 그대로 재려면 목표를 여기보다 뒤로 물릴 이유가 없다 —
   * 규칙 2가 스폰 지점도 찍을 수 있다고 명시하므로 이 셀은 유효한 명령이다.
   * (격자 밖 좌표는 moveAlly가 거부하므로 여기서 한 번 더 자른다 — 명령이 조용히
   *  씹히면 'front' 팔이 사실은 'home' 팔이 되어 봉투 12번이 공허해진다)
   */
  const frontCell: { x: number; z: number } = (() => {
    const wp = stage.paths[0]?.[0] ?? stage.baseCell;
    return {
      x: Math.min(stage.gridW - 1, Math.max(0, wp.x)),
      z: Math.min(stage.gridH - 1, Math.max(0, wp.z)),
    };
  })();
  const allyOrder: AllyId[] =
    allyPolicy === undefined || allyPolicy.pick === undefined || allyPolicy.pick === 'rotate'
      ? ['clubber', 'slinger', 'guardian']
      : [allyPolicy.pick];
  /**
   * 공중 위협이 있을 때 고를 종 — allyOrder 중 **대공이 되는 것만** (15단계).
   *
   * 왜 주입 표가 아니라 모듈 상수 ALLY_DEFS로 판정하는가: 위약 대조군(PLACEBO_ALLIES)은
   * `canTargetAir`를 0으로 지운다. 주입 표를 읽으면 위약 팔에서 이 목록이 비어 진짜 팔과
   * **다른 카드**를 뽑고, 그러면 두 팔의 골드 흐름이 갈라져 위약 실험의 전제
   * ("같은 골드를 같은 시점에 태운다")가 깨진다. 사람 쪽 근거도 같다 — 누가 대공인지는
   * 카드에 적혀 있는 **지식**이지 전투에서 관측하는 결과가 아니다.
   *
   * `pick`으로 종을 못 박은 통제 실험은 이 규칙이 건드리지 않는다: 그 경우 allyOrder가
   * 한 종뿐이라 목록이 비거나(대공 아님 → 폴백) 같은 종 하나이거나 둘 중 하나다.
   */
  const allyAntiAir: AllyId[] = allyOrder.filter((id) => ALLY_DEFS[id].canTargetAir);
  let allyTurn = 0;

  // ══ 채집 팔 — 정책 전문은 GatherPolicy 주석에 있다 ══
  //  ⚠ 규칙 8(sim 자동 채집)이 들어오면서 **이 블록의 8할이 사라졌다.** 지운 것:
  //    후보 칸 목록(gatherCells) · 예약 장부(gatherClaim/gatherClaimed/gatherTaken) ·
  //    귀환 장부(gatherHoming) · 스텁(gatherCarry/gatherCarryGold/stepGatherStub) ·
  //    개체 지시 루프(nextGatherCell/sendHome/busyOf/carryOf/syncTaken/syncClaims).
  //    전부 **도달 불가 코드**였다 — 외곽 루프가 120틱마다 깨어날 때 sim 자동이 이미
  //    그 사람에게 일감을 붙여 놨기 때문이다(busyOf가 언제나 true). 남기면 다음 사람이
  //    `18.*` 값을 없는 정책 탓으로 읽는다.
  const gatherPolicy = opts.gather;
  const gatherDefId: AllyId = gatherPolicy?.defId ?? 'gatherer';
  /**
   * ⚠ 타입이 아니라 **표**로 판정한다. `AllyId`에 `'gatherer'`가 있어도 되돌리기
   * 대조군(`gather-off` 류)은 그 종을 표에서 빼 버릴 수 있고, 그때 이 팔이 조용히
   * 배포본 봇이 되면 대조군이 실험군을 돌려받는 사고가 된다.
   */
  const gatherDef: AllyDef | undefined = ALLY_DEFS[gatherDefId];
  const gatherOn = gatherPolicy !== undefined && gatherDef !== undefined;

  /**
   * 채집 판정 — **외곽 루프(120틱)에 얹는다**(§9-3). prep 전용이 아니다:
   * prep은 90틱(3.0초)이라 채집꾼의 최단 캐기(4.0초)보다도 짧아서, phase를 보면
   * 채집이 통째로 웨이브 길이에 결합된다(§4-8 E-15).
   *
   * 규칙 8 뒤로 이 함수가 하는 일은 **인원 유지 하나뿐**이다. 캘 칸을 고르고 마을로
   * 돌려보내는 것은 전부 sim이 한다 — 그리고 그것이 배포본 게임이다.
   */
  const stepGather = (): void => {
    if (!gatherOn || gatherPolicy === undefined) return;
    const st = sim.state;
    if (st.phase !== 'wave' && st.phase !== 'prep') return;
    // 인원 유지. ⚠ `trainAlly`가 false면 **재시도하지 않는다** — 정원이 막은 것이고
    //    (STRONG_BOT 팔은 Lv1이라 정원 2다) 같은 루프에서 다시 눌러도 같은 false가 온다.
    let alive = 0;
    for (const a of st.allies) if (a.alive && a.defId === gatherDefId) alive++;
    if (alive < gatherPolicy.count && sim.canTrainAlly(gatherDefId)) {
      const cost = sim.allyCost(gatherDefId);
      if (cmd({ type: 'trainAlly', defId: gatherDefId })) {
        // 채집꾼도 부족원이다 — goldAllies에 안 넣으면 goldEarned 항등식이 어긋난다
        goldAllies += cost;
        alliesTrained++;
      }
    }
  };

  /** 채집 이탈 시간 계측 — 상태는 sim이 들고 있으므로 **세기만 한다** */
  const stepGatherTicks = (): void => {
    for (const a of sim.state.allies) {
      if (!a.alive || a.defId !== gatherDefId) continue;
      if ((a.gatherKey ?? -1) >= 0 || (a.carryCount ?? 0) > 0) allyGatherTicks++;
    }
  };

  /**
   * 아군 출동 판정 — "마을 앞까지 온 적이 있으면 뽑는다".
   * 전진 중인 적만이 아니라 **이미 봉쇄된 적도** 트리거로 센다: 앞줄이 붙잡고 있는
   * 동안 뒷사람을 채워 넣지 않으면 줄이 한 명씩 갈려 나가기만 한다.
   *
   * ── 15단계: **비행 적을 아예 못 보던 맹점을 고쳤다** ───────────────────────
   * 예전 판정은 `if (e.flying) continue`라 하늘길로 웨이브가 통째로 들어와도 봇은
   * "위험이 없다"고 읽고 아군을 한 명도 안 뽑았다. 그건 정책이 아니라 **자의 버그**다 —
   * 봇이 화면에 보이는 위협의 절반을 못 보면 그 봇으로 잰 난이도는 게임의 난이도가 아니다.
   * 이제 지상·공중을 함께 세고(각자 자기 경로 길이로 남은 거리를 잰다),
   * 공중이 섞여 있으면 **대공이 되는 종**을 고른다.
   * ⚠ 비행 적이 없는 스테이지에서는 `air`가 언제나 0이고 `near`도 예전과 같은 값이라
   *   **결과가 한 자리도 바뀌지 않는다**(스테이지1 기준 전 항목 무변으로 확인).
   */
  const stepAllies = (): void => {
    if (!allyPolicy) return;
    const st = sim.state;
    if (st.phase !== 'wave') return;
    // 9단계: 정원은 **마을 레벨의 함수**다 — 공개 상태의 allyCap 필드는 갱신되지 않으므로
    // 반드시 메서드를 읽는다 (BotOptions.allies.max 주석의 ⚠).
    const max = allyPolicy.max ?? sim.allyCap();
    if (st.allies.length >= max) return;
    let near = 0;
    let air = 0;
    for (const e of st.enemies) {
      const lens = e.flying ? airLens : pathLens;
      const len = lens[e.pathIndex] ?? lens[0] ?? 0;
      if (len - e.dist > allyTrigger) continue;
      near++;
      if (e.flying) air++;
    }
    if (near < allyMinNearNow) return;
    const order = air > 0 && allyAntiAir.length > 0 ? allyAntiAir : allyOrder;
    const defId = order[allyTurn % order.length] as AllyId;
    const cost = sim.allyCost(defId);
    if (st.gold - cost < allyReserve) return;
    if (!sim.canTrainAlly(defId)) return;
    if (cmd({ type: 'trainAlly', defId })) {
      goldAllies += cost;
      alliesTrained++;
      allyTurn++;
      /*
       * 자리 명령은 **출동 직후에만** 낸다 (9단계).
       * 매 판정마다 내지 않는 이유: moveAlly는 목표를 덮어쓰기만 하는 커맨드라 같은 셀을
       * 반복해 찍어도 결과가 같고, 그러면 이벤트만 수백 번 쌓인다. 새로 태어난 부족원은
       * 집결 지점을 목표로 갖고 나오므로(규칙 1) 그 한 명을 위해 한 번 내면 충분하다.
       * 대상을 −1(전원)로 두는 이유는 그게 사람이 실제로 누르는 버튼이기 때문이다 —
       * 여섯을 한 명씩 찍게 하면 급할 때 여섯 번을 눌러야 한다(규칙 2).
       */
      if (allyStance === 'front') {
        cmd({
          type: 'moveAlly',
          allyId: -1,
          cellX: frontCell.x,
          cellZ: frontCell.z,
        });
      }
    }
  };

  /** 홈타운 레벨업 판정 — 예비비를 남기고 다음 한 칸을 산다 */
  const stepBase = (): void => {
    const p = opts.base;
    if (!p) return;
    const st = sim.state;
    if (st.baseLevel >= (p.upTo ?? st.baseLevelMax)) return;
    const cost = sim.baseUpgradeCost();
    if (cost === null || st.gold - cost < (p.reserve ?? 0)) return;
    if (!sim.canUpgradeBase()) return;
    if (cmd({ type: 'upgradeBase' })) goldBase += cost;
  };

  /**
   * 이 카드로 지금 지을 최적의 빈 칸. 불도저 봇은 더 좋은 등급의 소품 칸을 만나면
   * (제거비 + 배치비)를 감당할 수 있는 한 골드를 내고 산다.
   */
  const pickCell = (towerId: TowerId, placeCost: number): [number, number] | undefined => {
    const def = TOWER_DEFS[towerId];
    let bestFree: [number, number] | undefined;
    let bestFreeKey = Infinity;
    let bestBuy: [number, number] | undefined;
    let bestBuyKey = Infinity;
    if (placeMode === 'kill') recountCover(); // 겹침 가중이 있는 정책에서만 필요하다
    for (const c of cells) {
      const key = keyOf(def, c);
      if (sim.canPlaceAt(c[0], c[1])) {
        if (key < bestFreeKey) {
          bestFreeKey = key;
          bestFree = c;
        }
      } else if (bulldoze && key < bestBuyKey) {
        const clear = sim.clearSceneryCost(c[0], c[1]);
        if (clear !== null && sim.state.gold >= clear + placeCost) {
          bestBuyKey = key;
          bestBuy = c;
        }
      }
    }
    // 소품을 치워서 얻는 자리가 **더 좋을 때만** 산다 (같거나 나쁘면 낭비)
    if (bestBuy && bestBuyKey < bestFreeKey) {
      const paid = sim.clearSceneryCost(bestBuy[0], bestBuy[1]) ?? 0;
      if (cmd({ type: 'clearScenery', cellX: bestBuy[0], cellZ: bestBuy[1] })) {
        clears++;
        clearGold += paid;
        return bestBuy;
      }
    }
    return bestFree;
  };

  const rawReserve = opts.towerReserve ?? 0;
  /**
   * 방어선(cap기) 이 다 서기 전에는 예비비가 없다 — 위 towerReserve 주석의 근거.
   * base.save 가 켜져 있으면 **다음 마을 레벨 값**도 타워가 못 건드리게 얹는다.
   */
  const reserveNow = (): number => {
    if (sim.state.towers.length < cap) return 0;
    let r = rawReserve;
    const p = opts.base;
    if (p?.save === true && sim.state.baseLevel < (p.upTo ?? sim.state.baseLevelMax)) {
      r += sim.baseUpgradeCost() ?? 0;
    }
    return r;
  };

  // ── 목표 구성 / 핸드 새로고침 (둘 다 지정하지 않으면 기본 봇과 한 틱도 다르지 않다) ──
  const comp = opts.comp;
  const refreshMaxPaid = opts.refresh?.maxPaid;
  /** 이 종의 할당량에서 몇 기가 모자란가 (할당량이 없으면 0 이하) */
  const deficitOf = (id: TowerId): number => {
    const want = comp?.[id] ?? 0;
    let have = 0;
    for (const t of sim.state.towers) if (t.defId === id) have++;
    return want - have;
  };
  /**
   * 이번 배치 판정에서 카드를 볼 순서.
   * comp가 있고 모자란 카드가 있으면 **부족분이 큰 순서**(동점이면 핸드 인덱스 순),
   * 아니면 기본 봇 그대로 **핸드 인덱스 순**이다.
   */
  const handOrder = (): number[] => {
    const st = sim.state;
    const plain = st.hand.map((_, i) => i).filter((i) => st.hand[i]);
    if (!comp) return plain;
    const want = plain
      .map((i) => ({ i, d: deficitOf((st.hand[i] as { towerId: TowerId }).towerId) }))
      .filter((e) => e.d > 0)
      .sort((a, b) => b.d - a.d || a.i - b.i);
    return want.length > 0 ? want.map((e) => e.i) : plain;
  };
  /** 핸드에 '할당량이 모자란 카드'가 하나라도 있는가 (새로고침을 도는 유일한 반대 조건) */
  const handHasWanted = (): boolean => {
    const st = sim.state;
    if (!comp) return true;
    return st.hand.some((c) => c && deficitOf(c.towerId) > 0);
  };

  const tryPlace = (goldFactor: number): void => {
    const st = sim.state;
    // 새로고침 — 방어선을 짓는 중이고, 원하는 카드가 하나도 없고, 값이 싸고, 예비비를 안 깰 때만.
    // 판당 실측 0.8회 · 4골드짜리 행동인데 봉투 헤더가 "핸드 드로우 운"이라 부른 패배를 지운다.
    if (refreshMaxPaid !== undefined && st.towers.length < cap) {
      for (let n = 0; n < REFRESH_MAX_PER_DECISION && !handHasWanted(); n++) {
        const cost = st.refreshCost;
        if (cost > refreshMaxPaid) break;
        if (st.gold - cost < reserveNow()) break;
        if (!cmd({ type: 'refreshHand' })) break;
        goldTowers += cost;
      }
    }
    for (const h of handOrder()) {
      const card = st.hand[h];
      if (!card) continue;
      if (st.gold < card.cost * goldFactor) continue;
      if (st.gold - card.cost < reserveNow()) continue;
      const cell = pickCell(card.towerId, card.cost);
      if (!cell) break;
      const paid = card.cost;
      if (cmd({ type: 'placeTower', handIndex: h, cellX: cell[0], cellZ: cell[1] })) {
        placed++;
        goldTowers += paid;
      }
      break;
    }
  };

  /**
   * 사건 집계 — 외곽 루프 끝(기본)이든 매 틱(계측 훅)이든 **같은 함수**가 처리한다.
   * 두 자리에 같은 코드를 두면 훅을 켠 판과 끈 판의 결과가 갈라질 수 있다.
   */
  const handleEvent = (ev: SimEvent, waveNow: number): void => {
    if (ev.type === 'gatherDelivered') {
      // ⚠ 채집이 골드를 내는 **유일한** 사건이다(§3-8 D3). T2 전에는 한 번도 안 온다.
      gatherEvents++;
      gatherDeliveries++;
      gatherGold += ev.gold;
      const b = bandOf(waveNow);
      gatherGoldByBand[b] = (gatherGoldByBand[b] ?? 0) + ev.gold;
      return;
    }
    if (ev.type === 'gathered') {
      gatherEvents++;
      gatherLoads++;
      // ⚠ **여기서 센다.** 재생 전에는 판 끝 스냅샷으로 갈음했지만(`taken`이 단조였다),
      //   재생이 그 등식을 깼다 — 스냅샷은 이제 "지금 비어 있는 칸 수"다(위 `harvests` 주석).
      harvests++;
      return;
    }
    if (ev.type === 'gatherRegrown') {
      gatherEvents++;
      regrows++;
      return;
    }
    if (ev.type === 'gatherStarted') {
      gatherEvents++;
      return;
    }
    if (ev.type === 'gatherLost') {
      gatherEvents++;
      if (ev.reason === 'died') {
        gatherDeaths++;
        gatherLostGold += ev.gold;
      }
      return;
    }
    if (ev.type === 'towerDestroyed') {
      destroyed++;
      lostTiers += ev.tier;
      lostGold += investedById.get(ev.towerId) ?? 0;
    } else if (ev.type === 'baseDamaged') {
      leaked += ev.amount;
    } else if (ev.type === 'enemyLeaked') {
      leaks++;
      gateTicksSum += gateEnter.get(ev.enemyId) ?? 0;
      gateEnter.delete(ev.enemyId);
    } else if (ev.type === 'enemyAtGate') {
      gateStints++;
      gateEnter.set(ev.enemyId, 0);
    } else if (ev.type === 'gateBite') {
      gateBites += ev.amount;
      gateEnter.set(ev.enemyId, ev.gateTicks);
    } else if (ev.type === 'baseFired') {
      baseShots++;
    } else if (ev.type === 'allyDied') {
      allyDeaths++;
    } else if (ev.type === 'enemyDamaged') {
      if (ev.source === 'hometown') baseDamage += ev.amount;
      lastHit.set(ev.enemyId, ev.source);
    } else if (ev.type === 'enemyDied') {
      if (lastHit.get(ev.enemyId) === 'hometown') baseKills++;
      lastHit.delete(ev.enemyId);
      if (ev.gateTicks !== undefined) {
        gateKills++;
        gateTicksSum += ev.gateTicks;
      }
      gateEnter.delete(ev.enemyId);
    }
  };
  const onEvent = opts.onEvent;

  let guard = 0;
  while (sim.state.phase !== 'won' && sim.state.phase !== 'lost' && guard < maxIters) {
    guard++;
    const st = sim.state;
    if (st.towers.length < cap) tryPlace(1);
    // 채집 판정 — **방어선 뒤 · 마을 앞**. 여기에 두는 이유는 stepBase와 같다("방어선은
    // 세우되 강화보다 먼저"). ⚠ 타워 업그레이드 **앞**이어야 한다: 업그레이드 루프는 매 회
    // 잔고를 0으로 훑어 가는 무한 흡수구라(towerReserve 주석), 뒤에 두면 채집꾼 70골드를
    // 영영 못 사고 이 팔이 **아무것도 안 재는 팔**이 된다.
    stepGather();
    // 홈타운 레벨업은 **웨이브 사이의 결정**이라 외곽 루프에 둔다 (UI도 기지 탭 패널이다).
    // 타워 배치 뒤·업그레이드 앞에 놓아 "방어선은 세우되 강화보다 먼저"가 되게 한다 —
    // 예비비(reserve)를 크게 주면 반대로 '남는 돈으로만' 사는 봇이 된다.
    stepBase();
    // 최다투자 타워 집중 업그레이드 (소수 정예)
    let best: { id: number; inv: number; cost: number } | null = null;
    for (const t of st.towers) {
      const c = sim.upgradeCost(t.id);
      if (c !== null && st.gold - c >= reserveNow() && (!best || t.invested > best.inv)) {
        best = { id: t.id, inv: t.invested, cost: c };
      }
    }
    if (best) {
      const paid = best.cost;
      if (cmd({ type: 'upgradeTower', towerId: best.id })) goldTowers += paid;
    } else if (st.towers.length >= cap) tryPlace(1.5);
    // 조기 호출: 성한 타워만 있을 때만 (손상 중이면 준비 시간을 수리로 쓴다)
    if (st.phase === 'prep' && st.prepTicksLeft > 0) {
      const damaged = opts.alwaysRush !== true && st.towers.some((t) => t.hp < t.maxHp);
      if (!damaged) cmd({ type: 'callWave' });
    }
    investedById.clear();
    for (const t of st.towers) investedById.set(t.id, t.invested);
    // 매물가는 외곽 루프마다 다시 읽는다 (사망·정원 변화가 여기서 잡힌다)
    menuStale = true;
    for (let i = 0; i < 120; i++) {
      const goldBeforeTick = sim.state.gold;
      sim.tick();
      const s = sim.state;
      totalTicks++;
      // 틱 안에서 골드는 **늘기만 한다**(지출은 전부 applyCommand다) — 그래서 양수 차가
      // 그대로 틱 수입이다: 현상금 · 웨이브 보상 · (T2 이후) 채집 배달.
      const dGold = s.gold - goldBeforeTick;
      if (dGold > 0) goldFromTicks += dGold;
      if (menuStale) {
        menuNow = menuPrice();
        menuStale = false;
      }
      if (menuNow > 0 && s.gold < menuNow) {
        brokeTicks++;
        brokeRun++;
        if (brokeRun > brokeRunMax) brokeRunMax = brokeRun;
        if (menuNow < brokePriceMin) brokePriceMin = menuNow;
        if (menuNow > brokePriceMax) brokePriceMax = menuNow;
      } else {
        brokeRun = 0;
      }
      if (s.phase === 'wave' && s.waveIndex >= MIN_TOWERS_FROM_WAVE && s.towers.length < minTowers) {
        minTowers = s.towers.length;
      }
      if (s.allies.length > 0) {
        allyTicks += s.allies.length;
        // 라벨대로 **교전 중인 아군 인원**을 센다 (한 명이 여러 마리를 묶어도 1)
        engaged.clear();
        for (const e of s.enemies) {
          if (e.blockerAllyId < 0) continue;
          enemyBlockedTicks++;
          engaged.add(e.blockerAllyId);
          // 입구 요격 감시 — 봉쇄 지점이 스폰(dist 0)에 얼마나 가까웠나
          if (e.dist < allyBlockMinDist) allyBlockMinDist = e.dist;
        }
        allyBlockTicks += engaged.size;
      }
      // 아군만 외곽 루프가 아니라 틱 루프 안에서 본다 — 한 판정이 한 명만 뽑으므로
      // 4초마다 보면 정원을 채우는 데 여러 웨이브가 걸린다 (ALLY_DECIDE_INTERVAL 주석)
      if (allyPolicy && i % ALLY_DECIDE_INTERVAL === 0) stepAllies();
      // 채집의 틱 쪽 — **세기만 한다.** sim을 한 번도 부르지 않는다(읽기만 한다).
      if (gatherOn) stepGatherTicks();
      // 계측 훅이 있을 때만 **매 틱** 비운다 — 웨이브 번호를 사건과 같은 틱에서 읽어야
      // "몇 번째 웨이브에서 맞았나"가 성립하기 때문이다. 훅이 없으면 한 줄도 안 돈다.
      if (onEvent) {
        for (const ev of sim.drainEvents()) {
          handleEvent(ev, sim.state.waveIndex);
          onEvent(ev, sim.state.waveIndex);
        }
      }
    }
    for (const ev of sim.drainEvents()) handleEvent(ev, sim.state.waveIndex);
  }
  const spent = goldTowers + goldAllies + goldBase + clearGold;
  return {
    won: sim.state.phase === 'won',
    wave: sim.state.waveIndex,
    clears,
    clearGold,
    destroyed,
    placed,
    lostTiers,
    lostGold,
    baseHpLeft: sim.state.baseHp,
    baseHpMax: sim.state.baseHpMax,
    baseLevel: sim.state.baseLevel,
    alliesTrained,
    allyDeaths,
    allyTicks,
    allyBlockTicks,
    enemyBlockedTicks,
    allyBlockMinDist,
    baseShots,
    baseDamage,
    baseKills,
    leaked,
    gateStints,
    gateTicks: gateTicksSum,
    gateBites,
    gateKills,
    leaks,
    goldTowers,
    goldAllies,
    goldBase,
    goldScenery: clearGold,
    goldEarned: spent + sim.state.gold - stage.startGold,
    minTowers: minTowers === Infinity ? 0 : minTowers,
    gatherGold,
    gatherLoads,
    gatherDeliveries,
    gatherLostGold,
    gatherDeaths,
    harvests,
    regrows,
    gatherGoldByBand,
    allyGatherTicks,
    gatherEvents,
    cmdCounts: Object.fromEntries([...cmdCounts.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))),
    cmdTotal,
    goldFromCommands,
    goldFromTicks,
    brokeTicks,
    totalTicks,
    brokeRunMax,
    brokePriceMin: brokePriceMin === Infinity ? 0 : brokePriceMin,
    brokePriceMax,
  };
}
