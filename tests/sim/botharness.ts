  totalTicks: number;
  /** **최장 무일푼 구간**(틱). 실측 기준선: 판별 중앙값 45.2초(1,356틱) · 최악 77.4초 */
  brokeRunMax: number;
  /** 무일푼 틱에서 관측된 최저 매물가의 **최솟값** (매물이 하나도 없었으면 0) */
  brokePriceMin: number;
